-- 标签管理表（poti_question 库）
-- 题目通过 question.tags 逗号分隔字段与标签名关联（多对多）
USE `poti_question`;

CREATE TABLE IF NOT EXISTS tag (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(50) NOT NULL COMMENT '标签名称',
  group_name VARCHAR(50) NOT NULL DEFAULT '' COMMENT '所属分组（算法/数据结构/公司/场景等，可选）',
  color VARCHAR(20) NOT NULL DEFAULT '' COMMENT '展示颜色',
  description VARCHAR(200) NOT NULL DEFAULT '' COMMENT '标签描述',
  sort INT NOT NULL DEFAULT 0 COMMENT '排序权重，越大越靠前',
  hot TINYINT NOT NULL DEFAULT 0 COMMENT '是否热门标签',
  status TINYINT NOT NULL DEFAULT 1 COMMENT '状态：1启用 0禁用',
  create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
  update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  deleted TINYINT NOT NULL DEFAULT 0,
  KEY idx_group_name (group_name),
  KEY idx_sort (sort),
  KEY idx_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='题目标签表';
